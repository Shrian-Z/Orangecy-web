import seed from '@/data/seed-50.json';
import type { Song } from '@/types';
import type { StudySource, StudyWord } from '@/lib/srs';

export interface FocusFragmentLine {
  text: string;
  time: number;
}

export interface FocusFragment {
  trackId: string;
  target: string;
  start: number;
  end: number;
  lines: FocusFragmentLine[];
}

export interface FocusCardData {
  w: string;
  p: string;
  m: string;
  s?: string;
  syn?: string[];
  exam?: [string, string];
  k?: string;
  /** Absent on imported words that no lyric in the user's library can sing. */
  track?: Song;
  fragment?: FocusFragment;
}

const deck = seed.cards as FocusCardData[];

/** The bundled deck is generated by scripts/build-cards.mjs and validated by
 * scripts/check-cards.mjs at build time; it is available synchronously so the
 * first painted frame is already a card. */
export function getFocusDeck() {
  return deck;
}

export function cardToStudyWord(card: FocusCardData): StudyWord {
  return {
    word: card.w,
    entry: {
      w: card.w,
      p: card.p,
      m: card.m,
      s: card.s,
      syn: card.syn,
      exam: card.exam,
    },
    source: sourceFromCard(card),
  };
}

export function sourceFromCard(card: FocusCardData): StudySource | undefined {
  if (!card.track || !card.fragment) return undefined;
  return {
    songId: card.track.id,
    songTitle: card.track.title,
    time: card.fragment.start,
    lineText: card.fragment.lines[0]?.text ?? '',
    song: card.track,
  };
}
