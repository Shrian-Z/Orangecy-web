import { chromium } from 'playwright-core';
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const ctx=await browser.newContext({viewport:{width:1440,height:900}});
await ctx.addInitScript(()=>{localStorage.setItem('orangecy.wordbook','cet4');localStorage.setItem('orangecy.cardsAutoplay','0');localStorage.setItem('orangecy.cardsSpeak','0');});
const page=await ctx.newPage();
await page.goto('http://localhost:5173/',{waitUntil:'networkidle'}); await page.waitForTimeout(1200);
await page.locator('.nav-item',{hasText:'词卡'}).first().click(); await page.waitForTimeout(1000);
console.log(await page.evaluate(()=>({scrollH:document.documentElement.scrollHeight,innerH:innerHeight,list:document.querySelector('.cards-wordlist')?.getBoundingClientRect().toJSON(), last:document.querySelector('.cards-word:last-child')?.getBoundingClientRect().toJSON()})));
await page.screenshot({path:'/tmp/cards-all-words.png'});
await browser.close();
